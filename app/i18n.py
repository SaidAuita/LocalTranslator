def tr(key: str, default: str = "") -> str:
    """Retrieve translated string for the current active UI language."""
    from app.config import config
    ui_lang = config.get("ui_language", "en")
    lang_map = TRANSLATIONS.get(ui_lang, TRANSLATIONS["en"])
    return lang_map.get(key, TRANSLATIONS["en"].get(key, default or key))
